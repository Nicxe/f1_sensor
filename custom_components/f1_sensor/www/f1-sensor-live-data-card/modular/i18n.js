const languageCode = language => String(language || 'en').toLowerCase().split('-', 1)[0];

export const words = (language, english, swedish = english) => {
  const code = languageCode(language);
  if (code === 'sv') return swedish;
  if (code !== 'nl') return english;
  const exact = DUTCH_OVERRIDES[english]
    ?? DUTCH_CATALOG_TRANSLATIONS[english]
    ?? DUTCH_TRANSLATIONS[english];
  if (exact) return exact;
  for (const [pattern, replacement] of DUTCH_PATTERNS) {
    if (pattern.test(english)) return english.replace(pattern, replacement);
  }
  return english;
};
